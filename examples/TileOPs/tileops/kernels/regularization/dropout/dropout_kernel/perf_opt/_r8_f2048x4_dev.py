import tilelang
import tilelang.language as T

ASCEND_MODE = "Developer"

tilelang.cache.clear_cache()

_F32 = "float32"
_A_I32 = -1640531527
_B_I32 = -2048144777
_M31 = 0x7FFFFFFF
# Expert: 20 AI cores x 2 AIV sub-blocks; each AIV is one persistent stream.
_BLOCKS = 40
_STREAMS = 40
_DEFAULT_BLOCK_SIZE = {"float32": 2048, "float16": 2048, "bfloat16": 2048}
_TORCH_DTYPE = {
    "float32": torch.float32,
    "float16": torch.float16,
    "bfloat16": torch.bfloat16,
}
_ATOL = {torch.float32: 1e-5, torch.float16: 1e-3, torch.bfloat16: 1.6e-2}
_RTOL = {torch.float32: 1e-5, torch.float16: 1e-3, torch.bfloat16: 1.6e-2}


# ---------- Golden (PyTorch CPU reference implementation) ----------
def golden_from_mask(x, mask, p):
    """Deterministic contract reference for a given 0/1 mask."""
    x_f = x.detach().cpu().to(torch.float32)
    m = mask.detach().cpu().to(torch.float32)
    scale = 0.0 if p >= 1.0 else 1.0 / (1.0 - p)
    return (x_f * (m * scale)).to(x.dtype)


def golden_dropout(x, p=0.5, training=True, seed=0):
    """torch contract baseline (p=0 identity / p=1 all zeros / training=False)."""
    del seed
    if not training or p == 0.0:
        return x.detach().cpu().clone()
    return F.dropout(x.detach().cpu().to(torch.float32), p, training=True).to(x.dtype)


# ---------- Kernel ----------
@functools.lru_cache(maxsize=32)
def _make_dropout_kernel(N, dtype, p, seed, default_block_size=2048):
    """Build the inverted-dropout kernel (NPU, ``target="npuir"``)."""
    del default_block_size
    scale = 1.0 / (1.0 - p) if p < 1.0 else 0.0
    tp = int(round(p * float(1 << 23)))
    tp_shift = 256 * tp - 1
    signed_mask = (p == 0.5)

    @tilelang.jit(out_idx=[1], target="npuir")
    def kernel(block_size):
        need_cast = dtype != _F32
        # fp16-only storage-dtype compute domain (p=0.5 -> 2.0).
        native_domain = need_cast and dtype == "float16" and (
            float(__import__("numpy").float16(scale)) == scale)
        md_extent = block_size if native_domain else 1
        xf_extent = block_size if need_cast else 1
        tp_extent = 1 if signed_mask else block_size
        n_num = T.ceildiv(N, block_size)
        n_grp = T.ceildiv(n_num, 4)
        n_iter = T.ceildiv(n_grp, _STREAMS)
        # Odd tile count: the last group re-processes a clamped
        # (idempotent, elementwise-deterministic) tile instead of a
        # runtime guard, so the hot loop stays branch-free.
        off_cap = max(N - block_size, 0)

        @T.prim_func
        def main(x: T.Tensor((N,), dtype), y: T.Tensor((N,), dtype)):
            with T.Kernel(40, is_npu=True) as (cid, _):
                x0 = T.alloc_ub((block_size,), dtype)
                x1 = T.alloc_ub((block_size,), dtype)
                x2 = T.alloc_ub((block_size,), dtype)
                x3 = T.alloc_ub((block_size,), dtype)
                y0 = T.alloc_ub((block_size,), dtype)
                y1 = T.alloc_ub((block_size,), dtype)
                y2 = T.alloc_ub((block_size,), dtype)
                y3 = T.alloc_ub((block_size,), dtype)
                f0 = T.alloc_ub((xf_extent,), _F32)
                f1 = T.alloc_ub((xf_extent,), _F32)
                f2 = T.alloc_ub((xf_extent,), _F32)
                f3 = T.alloc_ub((xf_extent,), _F32)
                c0 = f0 if need_cast else x0
                c1 = f1 if need_cast else x1
                c2 = f2 if need_cast else x2
                c3 = f3 if need_cast else x3
                lane = T.alloc_ub((block_size,), "int32")
                h0 = T.alloc_ub((block_size,), "int32")
                h1 = T.alloc_ub((block_size,), "int32")
                h2 = T.alloc_ub((block_size,), "int32")
                h3 = T.alloc_ub((block_size,), "int32")
                t0 = T.alloc_ub((block_size,), "int32")
                t1 = T.alloc_ub((block_size,), "int32")
                t2 = T.alloc_ub((block_size,), "int32")
                t3 = T.alloc_ub((block_size,), "int32")
                tp_b = T.alloc_ub((tp_extent,), "int32")
                mf0 = T.alloc_ub((block_size,), _F32)
                mf1 = T.alloc_ub((block_size,), _F32)
                mf2 = T.alloc_ub((block_size,), _F32)
                mf3 = T.alloc_ub((block_size,), _F32)
                md0 = T.alloc_ub((md_extent,), dtype)
                md1 = T.alloc_ub((md_extent,), dtype)
                md2 = T.alloc_ub((md_extent,), dtype)
                md3 = T.alloc_ub((md_extent,), dtype)

                # Loop-invariant constants (filled once).
                T.fill(tp_b, T.cast(tp_shift, "int32"))
                T.arange(lane, [1], 0)

                for i in T.serial(n_iter):
                    g = i * _STREAMS + cid
                    if g < n_grp:
                        t0_ = g * 4
                        off0 = t0_ * block_size
                        tail0 = T.min(block_size, N - off0)
                        off1 = T.min((t0_ + 1) * block_size, off_cap)
                        tail1 = T.min(block_size, N - off1)
                        off2 = T.min((t0_ + 2) * block_size, off_cap)
                        tail2 = T.min(block_size, N - off2)
                        off3 = T.min((t0_ + 3) * block_size, off_cap)
                        tail3 = T.min(block_size, N - off3)

                        # ---- PRNG: idx -> hash (right-shift-free, int32 wrap) ----
                        T.fill(h0, off0 + seed)
                        T.fill(h1, off1 + seed)
                        T.fill(h2, off2 + seed)
                        T.fill(h3, off3 + seed)
                        T.vadd(lane, h0, h0)
                        T.vadd(lane, h1, h1)
                        T.vadd(lane, h2, h2)
                        T.vadd(lane, h3, h3)
                        T.vmul(h0, _A_I32, h0)
                        T.vmul(h1, _A_I32, h1)
                        T.vmul(h2, _A_I32, h2)
                        T.vmul(h3, _A_I32, h3)
                        T.vshl(h0, 13, t0)
                        T.vshl(h1, 13, t1)
                        T.vshl(h2, 13, t2)
                        T.vshl(h3, 13, t3)
                        T.vxor(h0, t0, h0)
                        T.vxor(h1, t1, h1)
                        T.vxor(h2, t2, h2)
                        T.vxor(h3, t3, h3)
                        T.vmul(h0, _B_I32, h0)
                        T.vmul(h1, _B_I32, h1)
                        T.vmul(h2, _B_I32, h2)
                        T.vmul(h3, _B_I32, h3)
                        # ---- 0/1 mask ----
                        if signed_mask:
                            T.vclamp(h0, h0, 0, 1)
                            T.vclamp(h1, h1, 0, 1)
                            T.vclamp(h2, h2, 0, 1)
                            T.vclamp(h3, h3, 0, 1)
                            T.vcast(h0, mf0, round_mode="rint")
                            T.vcast(h1, mf1, round_mode="rint")
                            T.vcast(h2, mf2, round_mode="rint")
                            T.vcast(h3, mf3, round_mode="rint")
                        else:
                            T.vabs(h0, t0)
                            T.vabs(h1, t1)
                            T.vabs(h2, t2)
                            T.vabs(h3, t3)
                            T.vsub(t0, tp_b, t0)
                            T.vsub(t1, tp_b, t1)
                            T.vsub(t2, tp_b, t2)
                            T.vsub(t3, tp_b, t3)
                            T.vclamp(t0, t0, 0, 1)
                            T.vclamp(t1, t1, 0, 1)
                            T.vclamp(t2, t2, 0, 1)
                            T.vclamp(t3, t3, 0, 1)
                            T.vcast(t0, mf0, round_mode="rint")
                            T.vcast(t1, mf1, round_mode="rint")
                            T.vcast(t2, mf2, round_mode="rint")
                            T.vcast(t3, mf3, round_mode="rint")

                        # ---- data path (loads of all chains first) ----
                        T.copy(x[off0:off0 + tail0], x0[0:tail0])
                        T.copy(x[off1:off1 + tail1], x1[0:tail1])
                        T.copy(x[off2:off2 + tail2], x2[0:tail2])
                        T.copy(x[off3:off3 + tail3], x3[0:tail3])
                        if native_domain:
                            T.vcast(mf0, md0, round_mode="rint")
                            T.vcast(mf1, md1, round_mode="rint")
                            T.vcast(mf2, md2, round_mode="rint")
                            T.vcast(mf3, md3, round_mode="rint")
                            T.vmul(md0, T.cast(scale, dtype), md0)
                            T.vmul(md1, T.cast(scale, dtype), md1)
                            T.vmul(md2, T.cast(scale, dtype), md2)
                            T.vmul(md3, T.cast(scale, dtype), md3)
                            T.vmul(x0, md0, x0)
                            T.vmul(x1, md1, x1)
                            T.vmul(x2, md2, x2)
                            T.vmul(x3, md3, x3)
                            T.copy(x0[0:tail0], y[off0:off0 + tail0])
                            T.copy(x1[0:tail1], y[off1:off1 + tail1])
                            T.copy(x2[0:tail2], y[off2:off2 + tail2])
                            T.copy(x3[0:tail3], y[off3:off3 + tail3])
                        else:
                            if need_cast:
                                T.vcast(x0, c0, round_mode="rint")
                                T.vcast(x1, c1, round_mode="rint")
                                T.vcast(x2, c2, round_mode="rint")
                                T.vcast(x3, c3, round_mode="rint")
                            T.vmul(c0, T.cast(scale, _F32), c0)
                            T.vmul(c1, T.cast(scale, _F32), c1)
                            T.vmul(c2, T.cast(scale, _F32), c2)
                            T.vmul(c3, T.cast(scale, _F32), c3)
                            T.vmul(c0, mf0, c0)
                            T.vmul(c1, mf1, c1)
                            T.vmul(c2, mf2, c2)
                            T.vmul(c3, mf3, c3)
                            if need_cast:
                                T.vcast(c0, y0, round_mode="rint")
                                T.vcast(c1, y1, round_mode="rint")
                                T.vcast(c2, y2, round_mode="rint")
                                T.vcast(c3, y3, round_mode="rint")
                                T.copy(y0[0:tail0], y[off0:off0 + tail0])
                                T.copy(y1[0:tail1], y[off1:off1 + tail1])
                                T.copy(y2[0:tail2], y[off2:off2 + tail2])
                                T.copy(y3[0:tail3], y[off3:off3 + tail3])
                            else:
                                T.copy(c0[0:tail0], y[off0:off0 + tail0])
                                T.copy(c1[0:tail1], y[off1:off1 + tail1])
                                T.copy(c2[0:tail2], y[off2:off2 + tail2])
                                T.copy(c3[0:tail3], y[off3:off3 + tail3])

        return main
    return kernel


# ---------- test harness (same as the Stage 3/4 base file) ----------
def _run_kernel(x_cpu, dtype_str, p, seed, block_size=None):
    N = x_cpu.numel()
    if block_size is None:
        block_size = _DEFAULT_BLOCK_SIZE[dtype_str]
    kernel = _make_dropout_kernel(N, dtype_str, float(p), int(seed))
    fn = kernel(block_size)
    x_flat = x_cpu.reshape(-1).contiguous()
    return fn(x_flat.npu()).cpu()


def dropout_forward(x_cpu, dtype_str, p, seed, training=True, block_size=None):
    if not training:
        return x_cpu.detach().cpu().clone()
    return _run_kernel(x_cpu, dtype_str, p, seed, block_size)


def check_dropout_contract(y, x, p, y2=None):
    y = y.detach().cpu()
    x = x.detach().cpu()
    scale = 0.0 if p >= 1.0 else 1.0 / (1.0 - p)
    at = _ATOL[x.dtype]
    rt = _RTOL[x.dtype]
    yf = y.to(torch.float32)
    xf = x.to(torch.float32)
    is_zero = yf == 0
    is_scaled = torch.isclose(yf, xf * scale, atol=at, rtol=rt)
    structure_ok = bool((is_zero | is_scaled).all())
    n = x.numel()
    rate = float(((is_zero & (xf != 0)).to(torch.float32).sum() / max(n, 1)).item())
    sigma3 = 3.0 * (p * (1 - p) / n) ** 0.5 if 0 < p < 1 else 0.0
    rate_ok = bool(abs(rate - p) <= max(sigma3, 1e-6))
    replay_ok = None if y2 is None else bool(torch.equal(y, y2.detach().cpu()))
    return structure_ok, rate, rate_ok, replay_ok


def _assert_contract(y, x, p, tag, expect_rate=True, y2=None):
    structure_ok, rate, rate_ok, replay_ok = check_dropout_contract(y, x, p, y2)
    assert structure_ok, f"[{tag}] structure FAIL (dtype={x.dtype}, p={p})"
    if expect_rate:
        assert rate_ok, f"[{tag}] drop rate FAIL: rate={rate:.6f} vs p={p}"
    if replay_ok is not None:
        assert replay_ok, f"[{tag}] deterministic replay FAIL (same seed differs)"
    extra = "" if replay_ok is None else f" replay={replay_ok}"
    print(f"[{tag}] PASS dtype={x.dtype} p={p} N={x.numel()} rate={rate:.6f}{extra}")
    return rate


def _run_case(case_id, N, dtype_str, p, seed, *, block_size=None, kind="ones",
              expect_rate=None, replay=False):
    if expect_rate is None:
        expect_rate = kind == "ones"
    tdt = _TORCH_DTYPE[dtype_str]
    if kind == "ones":
        x = torch.ones(N, dtype=tdt)
    elif kind == "randn":
        x = torch.randn(N, dtype=tdt)
    else:
        raise ValueError(f"unknown kind {kind}")
    y = dropout_forward(x, dtype_str, p, seed, block_size=block_size)
    y2 = None
    if replay:
        y2 = dropout_forward(x, dtype_str, p, seed, block_size=block_size)
    _assert_contract(y, x, p, case_id, expect_rate=expect_rate, y2=y2)
    return y


