from tileops.utils import device_ascend_mode as _device_ascend_mode
from tileops.utils import scoped_ascend_mode as _scoped_ascend_mode

from ._moe_grouped_gemm_kernel import _moe_grouped_gemm_kernel as __moe_grouped_gemm_kernel_impl
from ._tile_scheduler_kernel import _tile_scheduler_kernel as __tile_scheduler_kernel_impl


def _pin_ascend_mode(impl, mode, export_name):
    """Pin TILELANG_ASCEND_MODE around the factory and its result.

    The mode is resolved through ``device_ascend_mode`` at call time so an
    Expert-pinned kernel compiles as Developer on A5, where the Expert
    codegen is broken for this source form (see tileops.utils.ascend_mode).
    """

    def _factory(*args, **kwargs):
        with _scoped_ascend_mode(_device_ascend_mode(mode)):
            factory = impl(*args, **kwargs)
        if not callable(factory):
            return factory

        def _call(*cargs, **ckwargs):
            with _scoped_ascend_mode(_device_ascend_mode(mode)):
                return factory(*cargs, **ckwargs)

        return _call

    _factory.__name__ = export_name
    return _factory


_moe_grouped_gemm_kernel = _pin_ascend_mode(__moe_grouped_gemm_kernel_impl, "Expert", "_moe_grouped_gemm_kernel")
_tile_scheduler_kernel = _pin_ascend_mode(__tile_scheduler_kernel_impl, "Developer", "_tile_scheduler_kernel")

