# ``_make_fused_gated_explicit`` above receives ``op_func(gate, value)``.  For
# SiluAndMulFwdKernel the GPU ``FusedGatedKernel._get_effective_op_func``
# builds that compound as ``activation_func(gate) * value`` -- i.e. the
