@functools.lru_cache(maxsize=32)
def gelu_and_mul_fwd_kernel(M, N, dtype, threads=256, num_per_thread=8):
    """FusedGated explicit_parallel: N elements per thread."""
    inv_sqrt2 = T.cast(INV_SQRT2, 'float32')

    @tilelang.jit(out_idx=[1])
    def kernel(threads_arg, npt_arg):
        block_N = threads_arg * npt_arg

        @T.prim_func
        def main(x: T.Tensor((M, 2 * N), dtype), y: T.Tensor((M, N), dtype)):
            with T.Kernel(T.ceildiv(N, block_N), M, threads=threads_arg) as (bx, by):
                for i, j in T.Parallel(threads_arg, npt_arg):
                    col = (bx * threads_arg + i) * npt_arg + j
                    gate = x[by, col]
                    value = x[by, N + col]
                    # Inlined GeluAndMulFwdKernel.activation_func: exact GELU
                    # (erf form) evaluated in fp32, then fused with ``* value``.
                    gate_f32 = T.Cast("float32", gate)
                    erf_val = T.Cast(gate.dtype, erf(gate_f32 * inv_sqrt2, gate.dtype))
                    y[by, col] = (
                        gate * T.cast(0.5, gate.dtype) * (T.cast(1.0, gate.dtype) + erf_val) * value
                    )
        return main
    return kernel

