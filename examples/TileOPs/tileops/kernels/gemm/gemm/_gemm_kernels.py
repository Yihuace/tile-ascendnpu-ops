class _Trace:
    """Minimal stand-in for the GPU-only ``tileops.trace`` timeline tracer.

    ``{gpu_repo_root}/tileops/trace/`` is an in-kernel timeline instrument
    with no NPU equivalent.  This stand-in mirrors the GPU *disabled*
    (untraced) behaviour so the marker calls embedded in ``_gemm_kernel``
    become no-ops: ``enabled`` is ``False``, ``out_idx`` returns the plain
    negative output index, ``finalize`` returns the prim_func unchanged, and
    the ``group`` / ``range`` scopes are empty context managers.  The NPU
    kernel component drops these calls during the ``target="npuir"``
    re-implementation.
    """

    _enabled = False

    @property
    def enabled(self) -> bool:
        return self._enabled

    @staticmethod
    def out_idx(n_outputs: int, traced: bool | None = None) -> list:
        enabled = _Trace._enabled if traced is None else traced
        n = n_outputs + 1 if enabled else n_outputs
        return list(range(-n, 0))

    @staticmethod
    @contextlib.contextmanager
    def group(name: str, lead: int = 0):
        yield

    @staticmethod
    @contextlib.contextmanager
    def range(name: str, lane: str | None = None):
        yield

    @staticmethod
    def dag(src: str, dst: str) -> None:
        return None

    @staticmethod
    def finalize(primfunc, traced: bool | None = None, max_events: int = 1024):
        return primfunc

    @staticmethod
    def run(compiled, inputs: tuple, *, stem: str | None = None):
        return compiled(*inputs)


trace = _Trace()
